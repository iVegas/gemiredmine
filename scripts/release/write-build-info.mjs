#!/usr/bin/env node
// Writes src/shared/build-info.generated.ts from package.json and the environment.
//
// Environment:
//   CHANNEL             stable | canary | unstable | dev (default: dev)
//   GITHUB_RUN_NUMBER   CI run number, used as the unstable build number
//   BUILD_DATE          override for reproducible builds (ISO 8601)
//   TARGET_PLATFORM     linux | windows (default: the host platform)
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { deriveBuildInfo, hostPlatform } from './channels.mjs';

const OUTPUT = fileURLToPath(new URL('../../src/shared/build-info.generated.ts', import.meta.url));
const DEV_PREVIEW_ENTRY = fileURLToPath(new URL('../../src/bun/dev-preview.generated.ts', import.meta.url));
const VIEW_DEV_PREVIEW_ENTRY = fileURLToPath(new URL('../../src/mainview/dev-preview.generated.ts', import.meta.url));
const PACKAGE_JSON = fileURLToPath(new URL('../../package.json', import.meta.url));

function gitCommit() {
  try {
    return execFileSync('git', ['rev-parse', '--short', 'HEAD'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return 'unknown';
  }
}

export function generateBuildInfo(env = process.env) {
  const { version } = JSON.parse(readFileSync(PACKAGE_JSON, 'utf8'));
  const info = deriveBuildInfo({
    packageVersion: version,
    channel: env.CHANNEL || 'dev',
    platform: env.TARGET_PLATFORM || hostPlatform(),
    buildNumber: Number(env.GITHUB_RUN_NUMBER || 0),
    commit: gitCommit(),
    buildDate: env.BUILD_DATE || new Date().toISOString(),
  });

  const source = [
    '// Generated by scripts/release/write-build-info.mjs. Do not edit; this file is gitignored.',
    "import type { BuildInfo } from './build-info';",
    '',
    `export const buildInfo: BuildInfo = ${JSON.stringify(info, null, 2)};`,
    '',
    '// A literal, so bundlers can remove developer-preview code from builds that never offer it.',
    `export const DEV_PREVIEW_AVAILABLE = ${info.devPreviewAvailable};`,
    '',
  ].join('\n');
  writeFileSync(OUTPUT, source);
  writeFileSync(DEV_PREVIEW_ENTRY, devPreviewEntry(info.devPreviewAvailable));
  writeFileSync(VIEW_DEV_PREVIEW_ENTRY, viewDevPreviewEntry(info.devPreviewAvailable));
  return info;
}

/**
 * The only module the Bun backend imports for the developer preview. Builds that do not
 * offer the preview get a stub that never references the implementation, so the
 * implementation is not bundled at all (bundlers do not reliably drop it otherwise).
 */
/** Webview counterpart: the settings panel and error reporting, absent from builds that do not offer the preview. */
export function viewDevPreviewEntry(available) {
  if (available) {
    return [
      '// Generated by scripts/release/write-build-info.mjs. Do not edit; this file is gitignored.',
      "export { default as DevPreviewPanel } from './components/DeveloperPreview.svelte';",
      "export { installDiagnosticsHooks } from './lib/diagnostics';",
      '',
    ].join('\n');
  }
  return [
    '// Generated by scripts/release/write-build-info.mjs. Do not edit; this file is gitignored.',
    '// This build does not offer the developer preview.',
    "import type DeveloperPreviewComponent from './components/DeveloperPreview.svelte';",
    '',
    'export const DevPreviewPanel = null as typeof DeveloperPreviewComponent | null;',
    'export const installDiagnosticsHooks = null as (() => void) | null;',
    '',
  ].join('\n');
}

export function devPreviewEntry(available) {
  if (available) {
    return [
      '// Generated by scripts/release/write-build-info.mjs. Do not edit; this file is gitignored.',
      "export { DevPreview } from './diagnostics/service';",
      '',
    ].join('\n');
  }
  return [
    '// Generated by scripts/release/write-build-info.mjs. Do not edit; this file is gitignored.',
    '// This build does not offer the developer preview, so the implementation is not included.',
    "import type { DevPreview as DevPreviewImplementation } from './diagnostics/service';",
    '',
    'export const DevPreview = undefined as unknown as typeof DevPreviewImplementation;',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const info = generateBuildInfo();
  console.log(`build-info: ${info.productName} ${info.version} (${info.channel}, ${info.commit})`);
}
